/**
 * Runtime strings of the agent runtime (zh-CN + en). Content text lives in
 * the case files as `LocalizedText`; everything the runtime itself says —
 * tool outputs, notifications, command output, offline responder phrasing,
 * deflections — is defined here.
 *
 * `rt(locale, key, params)` resolves a key for the closest supported locale
 * and substitutes `{name}` placeholders.
 */

import { EMBODIED_EN, EMBODIED_ZH } from "./i18n-embodied.js";

/** Runtime languages shipped with ClinicalCraft. */
export type RuntimeLang = "zh-CN" | "en";

/** Closest runtime language for a locale tag ("zh", "zh-Hans" → zh-CN; everything else → en). */
export function runtimeLang(locale: string | null | undefined): RuntimeLang {
  return locale && locale.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

/** True when the locale is Chinese. */
export function isZh(locale: string | null | undefined): boolean {
  return runtimeLang(locale) === "zh-CN";
}

/** Human-readable language name used in prompts ("always reply in …"). */
export function languageName(locale: string): string {
  const lower = locale.toLowerCase();
  if (lower.startsWith("zh")) return "Simplified Chinese (zh-CN)";
  if (lower.startsWith("en")) return "English";
  return locale;
}

