export type BenchMessageKey = Key;

/** Is this a Chinese locale? */
export function isZh(locale: string): boolean {
  return locale.toLowerCase().startsWith("zh");
}

/** A localised benchmark message with `{param}` placeholders filled. */
export function bm(locale: string, key: BenchMessageKey, params: Record<string, string | number> = {}): string {
  const template = (isZh(locale) ? ZH : EN)[key] ?? EN[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m));
}

